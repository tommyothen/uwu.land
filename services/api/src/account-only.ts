/**
 * True when a canonical hostname is an account-only destination or a
 * subdomain of one, so `user.pages.dev` matches but `pages.dev.evil.com` does
 * not.
 */
export function isAccountOnlyDestination(hostname: string): boolean {
	const labels = hostname.split(".");
	return labels.some((_, index) =>
		ACCOUNT_ONLY_DESTINATIONS.has(labels.slice(index).join("."))
	);
}
